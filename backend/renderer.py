def spherical_direction(rotation, elevation):
    """Blender world direction toward the camera.

    Rotation 0 faces the model's Roblox front (-Z, which imports as Blender +Y);
    positive rotation orbits toward Roblox +X, positive elevation looks from above.
    """
    rotation, elevation = math.radians(rotation), math.radians(elevation)
    return Vector((
        math.sin(rotation) * math.cos(elevation),
        math.cos(rotation) * math.cos(elevation),
        math.sin(elevation),
    ))


def view_direction(rotation, elevation):
    """Camera-space direction: x right, y up, z toward the viewer."""
    rotation, elevation = math.radians(rotation), math.radians(elevation)
    return Vector((
        math.sin(rotation) * math.cos(elevation),
        math.sin(elevation),
        math.cos(rotation) * math.cos(elevation),
    )).normalized()


def get_camera():
    scene = bpy.context.scene
    camera = scene.objects.get("PreviewCamera")
    if camera is None:
        camera_data = bpy.data.cameras.new("PreviewCamera")
        camera = bpy.data.objects.new("PreviewCamera", camera_data)
        scene.collection.objects.link(camera)
    scene.camera = camera
    return camera


def configure_camera(center, size, settings):
    camera = get_camera()
    camera_data = camera.data
    orthogonal = settings["orthographic"]

    camera_data.type = "ORTHO" if orthogonal else "PERSP"
    camera_data.sensor_fit = "HORIZONTAL"

    diameter = max(
        size.x,
        size.y,
        size.z,
        0.01,
    )

    camera_data.ortho_scale = (
        diameter * CAMERA_PADDING / settings["zoom"]
    )

    distance = diameter * 5.0
    if not orthogonal:
        if settings["fovAuto"]:
            # Match the orthographic framing at the model's center plane.
            camera_data.lens = (
                camera_data.sensor_width * distance / camera_data.ortho_scale
            )
        else:
            camera_data.angle = math.radians(settings["fov"])
            distance = (camera_data.ortho_scale / 2) / math.tan(camera_data.angle / 2)

    direction = spherical_direction(settings["cameraRotation"], settings["cameraElevation"])
    camera.location = center + direction * distance
    look = (-direction).to_track_quat("-Z", "Y")
    roll = Quaternion((0.0, 0.0, 1.0), math.radians(settings["cameraRoll"]))
    camera.rotation_mode = "QUATERNION"
    camera.rotation_quaternion = look @ roll

    camera_data.clip_start = max(
        min(diameter * 0.001, distance * 0.01),
        0.0001,
    )

    camera_data.clip_end = max(
        distance + diameter * 30.0,
        1000.0,
    )
    bpy.context.view_layer.update()
    return camera


