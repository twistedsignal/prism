def prepare_uv_maps(obj):
    mesh = obj.data

    if not hasattr(mesh, "uv_layers"):
        return False

    if len(mesh.uv_layers) == 0:
        print(
            f"WARNING: {obj.name} has no UV map."
        )
        return False

    # OBJ import creates the UV layer from vt coordinates.
    # Make absolutely sure one is active.
    uv = mesh.uv_layers.active

    if uv is None:
        uv = mesh.uv_layers[0]
        mesh.uv_layers.active = uv

    try:
        uv.active_render = True
    except Exception:
        pass

    print(
        f"  UV: {obj.name} -> {uv.name}"
    )

    return True


