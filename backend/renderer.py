# Settings that change the rasterized text shape. Position offsets shift its cached mask later.
TEXT_KEYS = ("text", "textFont", "textSize", "textRotation", "textWeight", "textBold", "textItalic",
             "textUnderline", "textStrikethrough", "textLetterSpacing", "textLineSpacing", "textEmojiProvider")
# Synthetic styles, in units of the font size, when the font has no matching face.
ITALIC_SHEAR = 0.2
WEIGHT_OFFSET_PER_100 = 0.01
UNDERLINE_POSITION = -0.1
STRIKE_POSITION = 0.25
LINE_HEIGHT = 0.05


class TextLayer:
    """Renders the text overlay as a coverage mask in its own Workbench scene."""

    def __init__(self):
        self.scene = None
        self.objects = []
        self.sprites = RenderCache(8 * 1024 * 1024)

    def ensure_scene(self):
        if self.scene is not None:
            return self.scene
        scene = bpy.data.scenes.new("Prism Text")
        camera_data = bpy.data.cameras.new("Prism Text Camera")
        camera_data.type = "ORTHO"
        # The image spans one unit, so sizes are fractions of the image width.
        camera_data.ortho_scale = 1.0
        camera = bpy.data.objects.new("Prism Text Camera", camera_data)
        camera.location = (0.0, 0.0, 5.0)
        scene.collection.objects.link(camera)
        scene.camera = camera
        scene.render.engine = "BLENDER_WORKBENCH"
        shading = scene.display.shading
        shading.light = "FLAT"
        shading.color_type = "SINGLE"
        shading.single_color = (1.0, 1.0, 1.0)
        shading.show_cavity = False
        shading.show_shadows = False
        shading.show_specular_highlight = False
        scene.render.film_transparent = True
        scene.render.resolution_percentage = 100
        scene.render.image_settings.file_format = "PNG"
        scene.render.image_settings.color_mode = "RGBA"
        scene.render.image_settings.color_depth = "8"
        scene.render.image_settings.compression = 0
        scene.view_settings.view_transform = "Standard"
        self.scene = scene
        return scene

    def clear(self):
        for obj in self.objects:
            curve = obj.data
            bpy.data.objects.remove(obj, do_unlink=True)
            bpy.data.curves.remove(curve)
        self.objects = []

    def add_text(self, body, settings, font, size, shear, offset, underline, position):
        curve = bpy.data.curves.new("Prism Text", type="FONT")
        if font is not None:
            curve.font = font
        curve.body = body
        curve.align_x = "CENTER"
        curve.align_y = "CENTER"
        curve.size = size
        curve.shear = shear
        curve.offset = offset
        curve.space_character = settings["textLetterSpacing"]
        curve.space_line = settings["textLineSpacing"]
        if underline:
            for character in curve.body_format:
                character.use_underline = True
            curve.underline_position = position
            curve.underline_height = LINE_HEIGHT
        obj = bpy.data.objects.new("Prism Text", curve)
        # Positive rotation turns clockwise, as in Roblox.
        obj.rotation_euler = (0.0, 0.0, -math.radians(settings["textRotation"]))
        self.scene.collection.objects.link(obj)
        self.objects.append(obj)
        return obj

    def mixed_text(self, body, settings, font, size, shear, offset):
        """Place font runs and image glyphs on shared baselines before rotation."""
        rotation = math.radians(settings["textRotation"])
        cosine, sine = math.cos(rotation), math.sin(rotation)

        def rotate(x, y):
            return cosine * x + sine * y, -sine * x + cosine * y

        def measure(text):
            obj = self.add_text(text, settings, font, size, shear, offset, False, 0)
            obj.rotation_euler = (0, 0, 0)
            self.scene.view_layers[0].update()
            width = obj.dimensions.x
            self.objects.remove(obj)
            curve = obj.data
            bpy.data.objects.remove(obj, do_unlink=True)
            bpy.data.curves.remove(curve)
            return width

        marker = measure("|")
        lines = body.split("\n")
        line_height = size * 1.2 * settings["textLineSpacing"]
        placements = []
        for index, line in enumerate(lines):
            runs = list(emoji.tokens(line))
            widths = [size * settings["textLetterSpacing"] if image else max(0, measure(text + "|") - marker)
                      for text, image in runs]
            x = -sum(widths) / 2
            y = ((len(lines) - 1) / 2 - index) * line_height - size * 0.35
            for (text, image), width in zip(runs, widths):
                if image:
                    placements.append((text, rotate(x + width / 2, y + size * 0.4), size * 0.9))
                else:
                    obj = self.add_text(text, settings, font, size, shear, offset, settings["textUnderline"], UNDERLINE_POSITION)
                    obj.data.align_x = "LEFT"
                    obj.data.align_y = "TOP_BASELINE"
                    obj.location.x, obj.location.y = rotate(x, y)
                    if settings["textStrikethrough"]:
                        strike = self.add_text(text, settings, font, size, shear, offset, True, STRIKE_POSITION)
                        strike.data.align_x = "LEFT"
                        strike.data.align_y = "TOP_BASELINE"
                        strike.location = obj.location
                x += width
        return placements

    def render(self, directory, settings, size, aa):
        """Return the text coverage as an (h, w) array, rows bottom first."""
        scene = self.ensure_scene()
        self.clear()
        weight = min(900, settings["textWeight"] + (300 if settings["textBold"] else 0))
        italic = settings["textItalic"]
        resolved = fonts.resolve(settings["textFont"], weight, italic)
        font = None
        face_weight, face_italic = 400, False
        if resolved is not None:
            path, face_weight, face_italic = resolved
            try:
                font = bpy.data.fonts.load(path, check_existing=True)
            except RuntimeError:
                font, face_weight, face_italic = None, 400, False
        text_size = settings["textSize"] / REFERENCE_RESOLUTION
        shear = ITALIC_SHEAR if italic and not face_italic else 0.0
        offset = max(-0.04, (weight - face_weight) / 100 * WEIGHT_OFFSET_PER_100) * text_size
        body = emoji.decode_text(settings["text"])
        placements = []
        if any(image for _, image in emoji.tokens(body)):
            placements = self.mixed_text(body, settings, font, text_size, shear, offset)
        else:
            self.add_text(body, settings, font, text_size, shear, offset, settings["textUnderline"], UNDERLINE_POSITION)
        if settings["textStrikethrough"] and not placements:
            # Blender has no strikethrough: overlay an identical copy whose underline sits mid-height.
            self.add_text(body, settings, font, text_size, shear, offset, True, STRIKE_POSITION)

        scene.render.resolution_x = size
        scene.render.resolution_y = size
        scene.display.render_aa = aa
        path = Path(directory) / "text.png"
        scene.render.filepath = str(path)
        try:
            bpy.ops.render.render(write_still=True, scene=scene.name)
            mask = np.ascontiguousarray(load_png_pixels(path)[..., 3])
            if not placements:
                return mask
            colored = np.zeros((size, size, 4), dtype=np.float32)
            monochrome = np.zeros_like(colored)
            for sequence, (x, y), side in placements:
                asset = emoji.asset(sequence, settings["textEmojiProvider"])
                sprite = self.sprites.get(str(asset))
                if sprite is None:
                    sprite = load_png_pixels(asset)
                    self.sprites.put(str(asset), sprite)
                target = monochrome if sequence in ("\ue001", "\ue002", "\ue003") else colored
                emoji.place(target, sprite, ((x + 0.5) * size, (y + 0.5) * size), side * size, settings["textRotation"])
            mask = np.maximum(mask, monochrome[..., 3])
            return np.concatenate((colored, mask[..., None]), axis=2)
        finally:
            self.clear()


class Renderer:
    """Keeps imported models loaded so settings changes only re-render.

    Each model lives in its own collection; only the one being rendered is visible.
    """

    # Each loaded model keeps its meshes and textures in memory; older ones are re-imported on demand.
    MAX_MODELS = 2

    def __init__(self):
        clear_scene()
        self.models = {}
        self.studio_lights = StudioLights()
        self.directory = tempfile.TemporaryDirectory(prefix="renderer-")
        self.passes = RenderCache(max_bytes=24 * 1024 * 1024)
        self.base_renders = RenderCache(max_bytes=16 * 1024 * 1024)
        self.effect_masks = RenderCache(max_bytes=8 * 1024 * 1024)
        self.text = TextLayer()

    def load(self, input_path):
        """Import an OBJ once; returns its key for render()."""
        key = str(Path(input_path).resolve())
        model = self.models.pop(key, None)
        if model is None:
            # Free the oldest scene before importing the next one, so peak RSS
            # does not include an extra model during a switch.
            while len(self.models) >= self.MAX_MODELS:
                self.unload(next(iter(self.models)))
            model = self.import_model(Path(key))
        # Dicts keep insertion order, so re-inserting marks the model as most recent.
        self.models[key] = model
        return key

    def import_model(self, path):
        scene = bpy.context.scene
        collection = bpy.data.collections.new(f"Model {path.parent.name}")
        scene.collection.children.link(collection)
        view_layer = bpy.context.view_layer
        view_layer.active_layer_collection = view_layer.layer_collection.children[collection.name]
        try:
            roblox_export = import_obj(path)
        finally:
            view_layer.active_layer_collection = view_layer.layer_collection

        objects = [obj for obj in collection.all_objects if obj.type == "MESH"]
        if not objects:
            self.remove_collection(collection)
            raise RuntimeError("OBJ imported but contains no mesh objects.")

        print_scene_info(objects)
        return {
            "collection": collection,
            "objects": objects,
            "meshes": [obj.data for obj in objects],
            "smooth_meshes": {},
            "matrices": [(obj, obj.matrix_world.copy()) for obj in objects],
            "materials": prepare_materials(objects, roblox_export),
        }

    def unload(self, key):
        model = self.models.pop(key, None)
        if model is not None:
            self.remove_collection(model["collection"])
            del model
            memory.release()

    def text_bounds(self, settings, size, aa):
        """Visible text glyph bounds in 512px preview coordinates."""
        settings = schema.normalize(settings)
        if "text" not in required_passes(settings):
            return None
        text_key = ("text", json.dumps({name: settings[name] for name in TEXT_KEYS}, sort_keys=True), size, aa)
        mask = self.passes.get(text_key)
        if mask is None:
            mask = self.text.render(self.directory.name, settings, size, aa)
            self.passes.put(text_key, mask)
        coverage = np.maximum(mask[..., 3], mask[..., 4]) if mask.ndim == 3 else mask
        ys, xs = np.nonzero(coverage > 0.1)
        if not len(xs):
            return None
        scale = REFERENCE_RESOLUTION / size
        return {
            "x": int(xs.min()) * scale + settings["textOffsetX"],
            "y": (size - 1 - int(ys.max())) * scale + settings["textOffsetY"],
            "width": (int(xs.max()) - int(xs.min()) + 1) * scale,
            "height": (int(ys.max()) - int(ys.min()) + 1) * scale,
        }

    @staticmethod
    def remove_collection(collection):
        for obj in list(collection.all_objects):
            bpy.data.objects.remove(obj, do_unlink=True)
        bpy.data.collections.remove(collection)
        bpy.data.orphans_purge(do_local_ids=True, do_linked_ids=True, do_recursive=True)

    def render(self, key, settings, size=512, aa="32", progress=None):
        """Render a loaded model; returns straight-alpha display RGBA, bottom row first."""
        model = self.models.get(key)
        if model is None:
            raise RuntimeError("Model is not loaded.")
        settings = schema.normalize(settings)
        geometry_settings = {name: value for name, value in settings.items() if name not in EFFECT_KEYS}
        cache_key = (key, json.dumps(geometry_settings, sort_keys=True), size, aa)
        cavity_keys = {"cavity", "minAngle", "worldRidge", "worldValley", "screenRidge", "screenValley"}
        base_settings = {name: value for name, value in geometry_settings.items() if name not in cavity_keys}
        base_key = (key, json.dumps(base_settings, sort_keys=True), size, aa)
        full_settings = {name: value for name, value in geometry_settings.items() if name != "minAngle"}
        full_key = (key, json.dumps(full_settings, sort_keys=True), size, aa)

        needed = required_passes(settings)
        total = 4 + len(needed)  # Setup, material detail, base image, effects, and optional passes.
        completed = 0
        def step(stage):
            nonlocal completed
            if progress:
                progress(stage, completed, total)
            completed += 1
        step("Preparing model")
        text_key = ("text", json.dumps({name: settings[name] for name in TEXT_KEYS}, sort_keys=True), size, aa)
        pass_keys = {"normals": ("normals", base_key), "depth": ("depth", base_key), "flat": ("flat", base_key),
                     "detail": ("detail", base_key), "text": text_key}
        passes = {name: self.passes.get(pass_keys[name]) for name in needed}
        if "text" in needed:
            step("Rendering text")
        if "text" in needed and passes["text"] is None:
            # The text scene is independent of the model, so it never needs the model set up.
            passes["text"] = self.text.render(self.directory.name, settings, size, aa)
            self.passes.put(text_key, passes["text"])
        pixels = self.base_renders.get(cache_key)
        if pixels is not None and all(value is not None for value in passes.values()):
            if progress:
                progress("Applying image effects", total - 1, total)
            return post_process_pixels(pixels, settings, size, self.effect_masks, cache_key, passes)

        for other in self.models.values():
            other["collection"].hide_render = other is not model
        apply_material_settings(model["materials"], settings)
        apply_geometry_settings(model, settings)
        rotate_model(model, (settings["pitch"], settings["yaw"], settings["roll"]))
        center, bounds = calculate_bounds(model["objects"])
        configure_camera(center, bounds, settings)
        configure_workbench(settings, self.studio_lights, size, aa)

        step("Rendering material detail")
        detail = None
        if any(state["detail"] is not None for state in model["materials"]):
            detail = self.passes.get(pass_keys["detail"])
            if detail is None:
                path = Path(self.directory.name) / "detail.png"
                render_detail(path, model["materials"])
                detail = load_png_pixels(path)[..., :3]
                self.passes.put(pass_keys["detail"], detail)
        step("Rendering base image")
        if pixels is None:
            pixels = render_pixels(self.directory.name, model["objects"], settings["minAngle"], self.passes, full_key, base_key)
            if detail is not None:
                pixels = pixels.copy()
                pixels[..., :3] *= detail
            self.base_renders.put(cache_key, pixels)
        for name, render in (("normals", render_surface_normals), ("depth", render_depth), ("flat", render_flat)):
            if name in needed:
                step(f"Rendering {name}")
            if name in needed and passes[name] is None:
                passes[name] = capture_pass(self.directory.name, name, model["objects"], render)
                if name == "flat" and detail is not None:
                    passes[name][..., :3] *= detail
                self.passes.put(pass_keys[name], passes[name])
        step("Applying image effects")
        free_render_result()
        return post_process_pixels(pixels, settings, size, self.effect_masks, cache_key, passes)


def free_render_result():
    """Release Blender's copy of the last render; Prism already read it from disk."""
    result = bpy.data.images.get("Render Result")
    if result is not None:
        result.buffers_free()


def capture_pass(directory, name, objects, render):
    path = Path(directory) / f"{name}.png"
    render(path, objects)
    return load_png_pixels(path) if name == "flat" else load_pass_pixels(path)


def to_rgba8_top_down(pixels):
    """Convert renderer output to top-down RGBA8 bytes, as EditableImage expects."""
    return (np.clip(pixels[::-1], 0.0, 1.0) * 255 + 0.5).astype(np.uint8).tobytes()


