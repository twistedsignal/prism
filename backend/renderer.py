def make_smooth_mesh(mesh):
    """Copy a mesh with merged split vertices, smooth shading and no custom normals."""
    import bmesh

    smooth = mesh.copy()
    smooth.name = f"{mesh.name}_smooth"
    bm = bmesh.new()
    try:
        bm.from_mesh(smooth)
        bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=1e-5)
        bm.to_mesh(smooth)
    finally:
        bm.free()
    for name in ("custom_normal",):
        attribute = smooth.attributes.get(name)
        if attribute is not None:
            smooth.attributes.remove(attribute)
    if smooth.has_custom_normals:
        smooth.normals_split_custom_set([(0.0, 0.0, 0.0)] * len(smooth.loops))
    smooth.shade_smooth()
    return smooth


def apply_geometry_settings(model, settings):
    levels = int(settings["subdivision"])
    for obj, original in zip(model["objects"], model["meshes"]):
        if settings["smooth"]:
            smooth = model["smooth_meshes"].get(original.name)
            if smooth is None:
                smooth = make_smooth_mesh(original)
                model["smooth_meshes"][original.name] = smooth
            obj.data = smooth
        else:
            obj.data = original

        modifier = obj.modifiers.get("Prism Subdivision")
        if levels == 0:
            if modifier is not None:
                obj.modifiers.remove(modifier)
            continue
        if modifier is None:
            modifier = obj.modifiers.new("Prism Subdivision", "SUBSURF")
        modifier.levels = levels
        modifier.render_levels = levels
    bpy.context.view_layer.update()


