def calculate_bounds(objects):
    points = []

    depsgraph = bpy.context.evaluated_depsgraph_get()

    for original_obj in objects:
        obj = original_obj.evaluated_get(depsgraph)

        for corner in obj.bound_box:
            world_corner = (
                obj.matrix_world
                @ Vector(corner)
            )

            points.append(world_corner)

    if not points:
        raise RuntimeError(
            "Could not calculate model bounds."
        )

    minimum = Vector((
        min(p.x for p in points),
        min(p.y for p in points),
        min(p.z for p in points),
    ))

    maximum = Vector((
        max(p.x for p in points),
        max(p.y for p in points),
        max(p.z for p in points),
    ))

    center = (
        minimum + maximum
    ) * 0.5

    size = maximum - minimum

    return center, size


def parent_depth(obj):
    depth = 0
    parent = obj.parent
    while parent is not None:
        depth += 1
        parent = parent.parent
    return depth


def stance_matrix(pitch, yaw, roll):
    """Roblox-style orientation (CFrame.fromOrientation: Y, then X, then Z) in Blender axes.

    Roblox X is Blender X, Roblox Y (up) is Blender Z and Roblox Z is Blender -Y.
    """
    return (
        Matrix.Rotation(math.radians(yaw), 4, "Z")
        @ Matrix.Rotation(math.radians(pitch), 4, "X")
        @ Matrix.Rotation(math.radians(-roll), 4, "Y")
    )


def rotate_model(model, angles):
    """Rotate the assembled model about its bounds center in world space.

    Always starts from the imported transforms so repeated renders don't accumulate.
    """
    # Restore parents before children so child world matrices stay correct.
    for obj, matrix in sorted(model["matrices"], key=lambda item: parent_depth(item[0])):
        obj.matrix_world = matrix
    bpy.context.view_layer.update()
    if not any(angles):
        return
    center, _ = calculate_bounds(model["objects"])
    transform = (
        Matrix.Translation(center)
        @ stance_matrix(*angles)
        @ Matrix.Translation(-center)
    )
    matrices = [(obj, transform @ obj.matrix_world) for obj in model["objects"]]

    # Snapshot world transforms first, then assign parents before children.
    for obj, matrix in sorted(matrices, key=lambda item: parent_depth(item[0])):
        obj.matrix_world = matrix
    bpy.context.view_layer.update()


