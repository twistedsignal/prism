def find_principled(material):
    if not material.use_nodes:
        return None

    for node in material.node_tree.nodes:
        if node.type == "BSDF_PRINCIPLED":
            return node

    return None


def find_base_color_image_node(material, principled):
    """
    Find the image texture that ultimately supplies Principled Base Color.

    Normally glTF produces:

        Image Texture
             |
             v
        Principled BSDF Base Color

    Sometimes there may be intermediate nodes, so this does a small
    recursive traversal backwards through the graph.
    """

    if principled is None:
        return None

    base_color = principled.inputs.get("Base Color")

    if base_color is None:
        return None

    if not base_color.is_linked:
        return None

    visited = set()

    def search_socket(socket):
        for link in socket.links:
            node = link.from_node

            if node in visited:
                continue

            visited.add(node)

            if node.type == "TEX_IMAGE":
                if node.image is not None:
                    return node

            # Search backwards through inputs.
            for input_socket in node.inputs:
                if input_socket.is_linked:
                    result = search_socket(input_socket)

                    if result is not None:
                        return result

        return None

    return search_socket(base_color)


