def import_obj(path):
    print(f"Importing OBJ: {path}")
    # Roblox exports Y-up OBJ files. Blender resolves mtllib and texture
    # paths relative to the OBJ/MTL files automatically.
    bpy.ops.wm.obj_import(
        filepath=str(path),
        forward_axis="NEGATIVE_Z",
        up_axis="Y",
    )
    with path.open(errors="replace") as source:
        return "Generated by Roblox Studio" in source.read(512)


