class StudioLights:
    """Register Workbench studio rigs without saving preferences, cached by settings."""

    def __init__(self):
        self.directory = tempfile.TemporaryDirectory(prefix="renderer-studio-")
        self.key = None
        self.name = None

    def get(self, settings):
        sun = self.light_color(settings["sunColor"], settings["sunIntensity"])
        secondary = self.light_color(settings["secondaryColor"], settings["secondaryIntensity"])
        ambient = self.light_color(settings["ambientColor"], settings["ambientIntensity"])
        key_direction = view_direction(settings["sunRotation"], settings["sunElevation"])
        specular = settings["specular"]
        # Camera-space direction, diffuse RGB, softness, specular RGB.
        lights = (
            (tuple(key_direction), sun, 1.0, tuple(c * specular for c in sun)),
            (tuple(FILL_LIGHT_DIRECTION), secondary, 1.0, tuple(c * specular for c in secondary)),
            (tuple(RIM_LIGHT_DIRECTION), secondary, 1.0, tuple(c * specular for c in secondary)),
        )
        key = (lights, ambient)
        preferences = bpy.context.preferences
        if key == self.key and self.name in preferences.studio_lights:
            return self.name
        previous = preferences.studio_lights.get(self.name) if self.name else None
        self.name = self.create(lights, ambient)
        self.key = key
        if previous is not None:
            preferences.studio_lights.remove(previous)
        return self.name

    @staticmethod
    def light_color(hex_color, intensity):
        # Studio light RGB values are linear light, not display-space colors.
        return tuple(schema.srgb_to_linear(c) * intensity for c in schema.hex_to_rgb(hex_color))

    def create(self, lights, ambient):
        preferences = bpy.context.preferences
        system = preferences.system
        light_properties = (
            "use", "direction", "diffuse_color", "specular_color", "smooth",
        )
        original_ambient = tuple(system.light_ambient)
        original_lights = [
            {
                name: tuple(getattr(light, name))
                if name.endswith("color") or name == "direction"
                else getattr(light, name)
                for name in light_properties
            }
            for light in system.solid_lights
        ]

        try:
            system.light_ambient = ambient
            for index, light in enumerate(system.solid_lights):
                light.use = index < len(lights)
                if light.use:
                    direction, diffuse, softness, specular = lights[index]
                    light.direction = direction
                    light.diffuse_color = diffuse
                    light.specular_color = specular
                    light.smooth = softness

            # Keep the preset until exit: Blender can load it lazily when
            # rendering, after the original preferences have been restored.
            # A unique name avoids reusing cached lighting on subsequent renders.
            with tempfile.NamedTemporaryFile(
                dir=self.directory.name, suffix=".sl", delete=False,
            ) as preset:
                studio_path = preset.name
            studio = preferences.studio_lights.new(studio_path)
        finally:
            system.light_ambient = original_ambient
            for light, values in zip(system.solid_lights, original_lights):
                for name, value in values.items():
                    setattr(light, name, value)

        # Reload the saved rig after restoring the editable default lights.
        preferences.studio_lights.remove(studio)
        studio = preferences.studio_lights.load(studio_path, "STUDIO")
        return studio.name


def configure_workbench(settings, studio_lights, size, aa):
    scene = bpy.context.scene

    scene.render.engine = "BLENDER_WORKBENCH"

    shading = scene.display.shading

    # ========================================================
    # THIS IS THE IMPORTANT PART
    # ========================================================

    shading.light = "STUDIO"
    shading.studio_light = studio_lights.get(settings)

    # Workbench will now use:
    #
    #   active Image Texture node
    #          +
    #   active UV map
    #
    # If no texture exists it automatically falls back to
    # the material's Viewport Display color.
    shading.color_type = "TEXTURE"

    # ========================================================
    # CAVITY
    # ========================================================

    shading.show_cavity = settings["cavity"] and any(settings[name] > 0 for name in (
        "worldRidge", "worldValley", "screenRidge", "screenValley",
    ))
    shading.cavity_type = "BOTH"

    shading.curvature_ridge_factor = settings["screenRidge"]
    shading.curvature_valley_factor = settings["screenValley"]
    # BOTH combines curvature with screen-space ambient occlusion.
    # Set both effects explicitly instead of inheriting Blender defaults.
    shading.cavity_ridge_factor = settings["worldRidge"]
    shading.cavity_valley_factor = settings["worldValley"]

    # ========================================================
    # LIGHTING
    # ========================================================

    # Keep the daylight direction consistent in the thumbnail's camera view.
    shading.use_studiolight_view_rotation = False
    shading.studiolight_rotate_z = 0.0

    shading.show_specular_highlight = settings["specular"] > 0

    # ========================================================
    # SHADOWS
    # ========================================================

    shading.show_shadows = settings["castShadows"]

