def roblox_surface_atlas_neutral(image):
    """Recognize the legacy 128 x 2048 surface-detail atlas by its pixels."""
    if tuple(image.size) != (128, 2048):
        return None
    pixels = np.empty(128 * 2048 * 4, dtype=np.float32)
    image.pixels.foreach_get(pixels)
    pixels = pixels.reshape(2048, 128, 4)
    border = pixels[0, :, :3]
    # The atlas's smooth surface is neutral midgray, not a gray albedo.
    if not np.allclose(border, 128 / 255, atol=1 / 255):
        return None
    return tuple(border.mean(axis=0))


def prepare_surface_atlas_uvs(objects, material):
    """Repeat U and clamp V for the legacy Roblox surface atlas."""
    # Workbench repeats both axes regardless of the image node's extension.
    # Keep out-of-range V inside the smooth border, away from wrap filtering.
    margin = 0.5 / 2048
    for obj in objects:
        uv = obj.data.uv_layers.active
        if uv is None:
            continue
        for face in obj.data.polygons:
            if obj.data.materials[face.material_index] != material:
                continue
            for loop_index in face.loop_indices:
                coord = uv.data[loop_index].uv
                coord.y = min(max(coord.y, margin), 1.0 - margin)


def has_transparency(image, cache):
    key = ("alpha", image.as_pointer())
    if key not in cache:
        width, height = image.size
        alpha = np.empty(width * height * 4, dtype=np.float32)
        image.pixels.foreach_get(alpha)
        cache[key] = bool(np.any(alpha[3::4] < 1.0))
    return cache[key]


def make_workbench_texture(image, rgba, cache, neutral=None, opaque=False):
    """Bake MTL Kd into the diffuse image, since Workbench ignores shaders."""
    key = (image.as_pointer(), tuple(rgba), neutral, opaque)
    if key in cache:
        return cache[key]
    # A white, fully opaque Kd leaves the image unchanged: reuse it instead of a copy.
    if neutral is None and tuple(rgba) == (1.0, 1.0, 1.0, 1.0) and not (opaque and has_transparency(image, cache)):
        cache[key] = image
        return image

    width, height = image.size
    if not width or not height:
        raise RuntimeError(f"Could not load diffuse texture: {image.filepath}")

    pixels = np.empty(width * height * 4, dtype=np.float32)
    image.pixels.foreach_get(pixels)
    pixels = pixels.reshape(-1, 4)
    rgb = pixels[:, :3]
    if neutral is not None:
        # Convert the atlas's neutral gray to white before applying Kd.
        # Leave ordinary diffuse maps on the standard MTL path.
        rgb = np.clip(rgb / np.asarray(neutral), 0.0, 1.0)
    # Byte-backed sRGB images expose encoded pixel values. Multiply colors
    # in linear space, then encode for the generated sRGB texture.
    if image.colorspace_settings.name == "sRGB":
        rgb = np.where(rgb <= 0.04045, rgb / 12.92,
                       ((rgb + 0.055) / 1.055) ** 2.4)
    rgb = np.maximum(rgb * np.asarray(rgba[:3]), 0.0)
    pixels[:, :3] = np.where(rgb <= 0.0031308, rgb * 12.92,
                            1.055 * rgb ** (1.0 / 2.4) - 0.055)
    if opaque:
        pixels[:, 3] = 1.0
    else:
        pixels[:, 3] *= rgba[3]

    tinted = bpy.data.images.new(
        f"{image.name}_workbench_{len(cache)}",
        width=width, height=height, alpha=True,
    )
    tinted.colorspace_settings.name = "sRGB"
    tinted.pixels.foreach_set(pixels.ravel())
    tinted.update()
    cache[key] = tinted
    return tinted


def prepare_materials(objects, roblox_export=False):
    """Expose MTL diffuse colors and tinted diffuse maps to Workbench.

    Returns per-material state so transparency can be toggled per render.
    """
    print("\n========== MATERIAL SETUP ==========")
    processed_materials = set()
    texture_cache = {}
    states = []

    for obj in objects:
        prepare_uv_maps(obj)
        for material in obj.data.materials:
            if material is None or material in processed_materials:
                continue
            processed_materials.add(material)

            # OBJ import preserves MTL Kd/d here, even with a linked texture.
            # Reading the shader's default is unsafe for linked glTF graphs.
            rgba = tuple(material.diffuse_color)
            principled = find_principled(material)
            # The importer stores MTL d on the shader's Alpha input, not the viewport color.
            alpha_input = principled.inputs.get("Alpha") if principled is not None else None
            if alpha_input is not None and not alpha_input.is_linked:
                rgba = (*rgba[:3], float(alpha_input.default_value))
            print(f"Material: {material.name}, diffuse: {rgba}")
            state = {"material": material, "rgba": rgba, "node": None, "detail": None}
            states.append(state)
            image_node = find_base_color_image_node(material, principled)
            if not material.use_nodes:
                continue
            # Material detail textures arrive as MTL map_Ke; Workbench ignores emission.
            emission = principled.inputs.get("Emission Color") if principled is not None else None
            for link in (emission.links if emission is not None else ()):
                if link.from_node.type == "TEX_IMAGE" and link.from_node.image is not None:
                    state["detail"] = link.from_node
                    print(f"  Material detail: {link.from_node.image.name}")

            nodes = material.node_tree.nodes
            for node in nodes:
                node.select = False
            # Do not pick a normal, roughness, or emission map as base color.
            nodes.active = None
            if image_node is None:
                print("  No diffuse texture. Using material color.")
                continue

            image = image_node.image
            neutral = roblox_surface_atlas_neutral(image) if roblox_export else None
            if neutral is not None:
                prepare_surface_atlas_uvs(objects, material)
                print("  Roblox surface atlas: neutral detail, clamped V")
            # Roblox full-color maps already contain the surface colors.
            # Exported Kd can be the part's skin/base color; multiplying it
            # into clothing and other painted areas adds an unwanted tint.
            texture_rgba = (
                (1.0, 1.0, 1.0, rgba[3])
                if roblox_export and neutral is None else rgba
            )
            preview_node = nodes.new("ShaderNodeTexImage")
            preview_node.name = "Workbench Diffuse"
            preview_node.label = "Workbench diffuse texture"
            preview_node.select = True
            nodes.active = preview_node
            state.update(
                node=preview_node, image=image, texture_rgba=texture_rgba,
                neutral=neutral, cache=texture_cache,
            )
            print(f"  Workbench texture: {image.name}")

    print(f"Materials: {len(states)}\n")
    return states


def apply_material_settings(states, settings):
    transparent = settings["transparency"]
    for state in states:
        material = state["material"]
        material.roughness = settings["roughness"]
        material.metallic = 0.0
        alpha = state["rgba"][3] if transparent else 1.0
        material.diffuse_color = (*state["rgba"][:3], alpha)
        material.surface_render_method = "BLENDED" if transparent else "DITHERED"
        if state["node"] is not None:
            state["node"].image = make_workbench_texture(
                state["image"], state["texture_rgba"], state["cache"],
                state["neutral"], opaque=not transparent,
            )


