def get_args():
    if "--" not in sys.argv:
        raise RuntimeError(
            "\nUsage:\n"
            "blender --background --python renderer.py "
            "-- model/model2/model.obj render.png "
            "[--settings settings.json] [--size 512] [--aa 32] "
            "[--zoom 1.0] [--rotation X Y Z] "
            "[--orthogonal | --no-orthogonal]\n"
        )

    parser = argparse.ArgumentParser(
        description="Render an OBJ with Blender Workbench.",
        prog="blender --background --python renderer.py --",
    )
    parser.add_argument("input_path", type=Path, help="Input OBJ file")
    parser.add_argument("output_path", type=Path, help="Output PNG file")
    parser.add_argument("--settings", type=Path, help="JSON file of render settings (see schema.py)")
    parser.add_argument("--size", type=int, default=512, help="Square output size in pixels (default: 512)")
    parser.add_argument("--aa", choices=AA_SAMPLES, default="32", help="Anti-aliasing samples (default: 32)")
    parser.add_argument(
        "--orthogonal", action=argparse.BooleanOptionalAction, default=None,
        help="Use an orthographic camera; --no-orthogonal uses perspective",
    )
    parser.add_argument("--zoom", type=float, help="Positive camera zoom multiplier; larger values zoom in")
    parser.add_argument(
        "--rotation", type=float, nargs=3, metavar=("X", "Y", "Z"),
        help="Model pitch, yaw and roll in degrees about Roblox X, Y (up) and Z",
    )
    args = parser.parse_args(sys.argv[sys.argv.index("--") + 1:])

    settings = {}
    if args.settings is not None:
        settings = json.loads(args.settings.read_text())
    if args.orthogonal is not None:
        settings["orthographic"] = args.orthogonal
    if args.zoom is not None:
        if not math.isfinite(args.zoom) or args.zoom <= 0:
            parser.error("--zoom must be finite and greater than zero")
        settings["zoom"] = args.zoom
    if args.rotation is not None:
        if not all(math.isfinite(angle) for angle in args.rotation):
            parser.error("--rotation angles must be finite")
        settings["pitch"], settings["yaw"], settings["roll"] = args.rotation
    if args.size <= 0:
        parser.error("--size must be positive")

    input_path = args.input_path.resolve()
    if not input_path.exists():
        raise FileNotFoundError(input_path)
    if input_path.suffix.lower() != ".obj":
        raise RuntimeError(f"Expected .obj, got: {input_path}")

    return input_path, args.output_path.resolve(), schema.normalize(settings), args.size, args.aa


